defmodule MobMidi.VirtualDevice do
  @moduledoc """
  Pure builder for the Android declaration of an app's own MIDI device.

  On Android a virtual MIDI device is a `MidiDeviceService` declared in the
  host app's `AndroidManifest.xml`; its name and ports live in the
  `res/xml` file the service's `<meta-data>` points to. mob_midi ships the
  service class (`io.mob.midi.MobMidiDeviceService`) but the per-app name and
  port layout must come from the host, so this module generates exactly those
  two pieces. `mix mob_midi.gen.virtual_device` writes them into the host's
  `android/` tree.

  Android port directions are from the app's point of view of *other* apps:
  an `<input-port>` is one other apps send into (the app receives), an
  `<output-port>` is one the app sends out of (other apps listen).

      {:ok, cfg} = MobMidi.VirtualDevice.validate(name: "Humdinger", inputs: 0, outputs: 1)
      MobMidi.VirtualDevice.device_xml(cfg)

  The app then opens the device with `MobMidi.open_virtual(socket, "Humdinger")`.
  """

  @typedoc "A validated virtual-device configuration."
  @type config :: %{
          name: String.t(),
          manufacturer: String.t(),
          port_name: String.t(),
          inputs: 0..16,
          outputs: 0..16
        }

  @resource "mob_midi_device"
  @service_class "io.mob.midi.MobMidiDeviceService"
  @begin_marker "<!-- mob_midi:virtual-device BEGIN (generated by mix mob_midi.gen.virtual_device) -->"
  @end_marker "<!-- mob_midi:virtual-device END -->"
  @max_ports 16
  @max_text_bytes 64
  @keys [:name, :inputs, :outputs, :manufacturer, :port_name]

  @doc "The `res/xml` resource name the service's `<meta-data>` points to."
  @spec resource_name() :: String.t()
  def resource_name, do: @resource

  @doc """
  Validates and normalises a configuration.

  Keys: `:name` (required), `:inputs` (0..16, default 0), `:outputs`
  (0..16, default 1), `:manufacturer` (default `"Mob"`), `:port_name`
  (default `:name`). At least one port is required.
  """
  @spec validate(keyword() | map()) :: {:ok, config()} | {:error, String.t()}
  def validate(opts) when is_list(opts) do
    if Keyword.keyword?(opts),
      do: validate(Map.new(opts)),
      else: {:error, "options must be a keyword list or a map"}
  end

  def validate(opts) when is_map(opts) do
    with :ok <- check_keys(opts),
         {:ok, name} <- fetch_name(opts),
         {:ok, manufacturer} <- text(:manufacturer, Map.get(opts, :manufacturer, "Mob")),
         {:ok, port_name} <- text(:port_name, Map.get(opts, :port_name, name)),
         {:ok, inputs} <- count(:inputs, Map.get(opts, :inputs, 0)),
         {:ok, outputs} <- count(:outputs, Map.get(opts, :outputs, 1)),
         :ok <- at_least_one_port(inputs, outputs) do
      {:ok,
       %{
         name: name,
         manufacturer: manufacturer,
         port_name: port_name,
         inputs: inputs,
         outputs: outputs
       }}
    end
  end

  def validate(_opts), do: {:error, "options must be a keyword list or a map"}

  defp check_keys(opts) do
    case Map.keys(opts) -- @keys do
      [] -> :ok
      unknown -> {:error, "unknown option(s): #{Enum.map_join(unknown, ", ", &inspect/1)}"}
    end
  end

  defp fetch_name(opts) do
    case Map.fetch(opts, :name) do
      {:ok, name} -> text(:name, name)
      :error -> {:error, "name is required"}
    end
  end

  defp text(key, value) when is_binary(value) do
    cond do
      value == "" ->
        {:error, "#{key} must not be empty"}

      not String.valid?(value) ->
        {:error, "#{key} must be valid UTF-8"}

      byte_size(value) > @max_text_bytes ->
        {:error, "#{key} must be at most #{@max_text_bytes} bytes"}

      String.match?(value, ~r/[\x00-\x1F\x7F]/) ->
        {:error, "#{key} must not contain control characters"}

      true ->
        {:ok, value}
    end
  end

  defp text(key, value), do: {:error, "#{key} must be a string, got: #{inspect(value)}"}

  defp count(_key, n) when is_integer(n) and n in 0..@max_ports, do: {:ok, n}

  defp count(key, n) when is_integer(n),
    do: {:error, "#{key} must be between 0 and #{@max_ports}, got: #{n}"}

  defp count(key, n), do: {:error, "#{key} must be an integer, got: #{inspect(n)}"}

  defp at_least_one_port(0, 0), do: {:error, "the device needs at least one input or output port"}
  defp at_least_one_port(_inputs, _outputs), do: :ok

  @doc """
  Port names for one direction: the port name alone for a single port,
  `"<port_name> <n>"` (1-based) when there are several.
  """
  @spec port_names(config(), :inputs | :outputs) :: [String.t()]
  def port_names(cfg, direction) when direction in [:inputs, :outputs] do
    case Map.fetch!(cfg, direction) do
      0 -> []
      1 -> [cfg.port_name]
      n -> Enum.map(1..n, &"#{cfg.port_name} #{&1}")
    end
  end

  @doc """
  The `res/xml/#{@resource}.xml` device-info document.

  `name` is set alongside `manufacturer`/`product` because Android copies every
  `<device>` attribute into the device properties and mob_midi matches
  `open_virtual/2` against `PROPERTY_NAME` first.
  """
  @spec device_xml(config()) :: String.t()
  def device_xml(cfg) do
    ports =
      Enum.map(port_names(cfg, :inputs), &port("input-port", &1)) ++
        Enum.map(port_names(cfg, :outputs), &port("output-port", &1))

    """
    <?xml version="1.0" encoding="utf-8"?>
    <!-- Generated by mix mob_midi.gen.virtual_device; edit the task options, not this file. -->
    <devices>
        <device manufacturer="#{escape(cfg.manufacturer)}" product="#{escape(cfg.name)}" name="#{escape(cfg.name)}">
    #{Enum.join(ports)}    </device>
    </devices>
    """
  end

  defp port(tag, name), do: ~s(        <#{tag} name="#{escape(name)}" />\n)

  @doc "The `<service>` element (unindented) declaring `#{@service_class}`."
  @spec service_xml(config()) :: String.t()
  def service_xml(cfg) do
    """
    <!-- MIDI device "#{comment_safe(cfg.name)}": #{cfg.inputs} input / #{cfg.outputs} output port(s), see res/xml/#{@resource}.xml -->
    <service
        android:name="#{@service_class}"
        android:exported="true"
        android:permission="android.permission.BIND_MIDI_DEVICE_SERVICE">
        <intent-filter>
            <action android:name="android.media.midi.MidiDeviceService" />
        </intent-filter>
        <meta-data
            android:name="android.media.midi.MidiDeviceService"
            android:resource="@xml/#{@resource}" />
    </service>
    """
  end

  @doc """
  Inserts the fenced service block just before `</application>`, replacing
  any block a previous run left. Idempotent.
  """
  @spec put_service(String.t(), config()) :: {:ok, String.t()} | {:error, String.t()}
  def put_service(manifest_xml, cfg) when is_binary(manifest_xml) do
    with {:ok, stripped} <- remove_service(manifest_xml),
         {:ok, at} <- closing_application(stripped) do
      {:ok, insert_block(stripped, at, cfg)}
    end
  end

  @doc "Removes the fenced service block, if any."
  @spec remove_service(String.t()) :: {:ok, String.t()} | {:error, String.t()}
  def remove_service(manifest_xml) when is_binary(manifest_xml) do
    begins = length(:binary.matches(manifest_xml, @begin_marker))
    ends = length(:binary.matches(manifest_xml, @end_marker))

    if begins == ends do
      {:ok, Regex.replace(block_regex(), manifest_xml, "")}
    else
      {:error, "unbalanced mob_midi:virtual-device markers in the manifest; fix them by hand"}
    end
  end

  # The block's leading indentation and trailing newline go with it, so
  # remove + insert round-trips byte for byte.
  defp block_regex do
    ~r/^[ \t]*#{Regex.escape(@begin_marker)}.*?#{Regex.escape(@end_marker)}[ \t]*\r?\n?/ms
  end

  defp closing_application(xml) do
    case :binary.matches(xml, "</application>") do
      [] -> {:error, "no </application> in the manifest"}
      matches -> {:ok, matches |> List.last() |> elem(0)}
    end
  end

  defp insert_block(xml, at, cfg) do
    {before, rest} = :erlang.split_binary(xml, at)
    {head, line} = split_last_line(before)

    # Tag alone on its line: reuse its indentation. Otherwise start a new line.
    if String.trim(line) == "" do
      head <> block(line <> "    ", cfg) <> line <> rest
    else
      before <> "\n" <> block("    ", cfg) <> rest
    end
  end

  defp split_last_line(text) do
    case :binary.matches(text, "\n") do
      [] ->
        {"", text}

      matches ->
        {pos, 1} = List.last(matches)
        :erlang.split_binary(text, pos + 1)
    end
  end

  defp block(indent, cfg) do
    [@begin_marker, String.trim_trailing(service_xml(cfg), "\n"), @end_marker]
    |> Enum.join("\n")
    |> String.split("\n")
    |> Enum.map_join(&(indent <> &1 <> "\n"))
  end

  defp escape(value) do
    value
    |> String.replace("&", "&amp;")
    |> String.replace("<", "&lt;")
    |> String.replace(">", "&gt;")
    |> String.replace("\"", "&quot;")
    |> String.replace("'", "&apos;")
  end

  # XML comments can't contain "--" and entities don't apply inside them.
  defp comment_safe(value), do: Regex.replace(~r/-(?=-)/, value, "- ")
end
